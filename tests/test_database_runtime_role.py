def test_runtime_database_role_has_data_access_without_schema_or_role_privileges():
    if engine.dialect.name != "postgresql":
        pytest.skip("Runtime database role restrictions are verified against PostgreSQL in CI")

    with engine.connect() as connection:
        role = connection.execute(
            text(
                """
                SELECT current_user, rolsuper, rolcreatedb, rolcreaterole, rolinherit, rolreplication, rolbypassrls,
                       has_database_privilege(current_user, current_database(), 'CREATE'),
                       has_schema_privilege(current_user, 'public', 'USAGE'),
                       has_schema_privilege(current_user, 'public', 'CREATE'),
                       has_table_privilege(current_user, 'users', 'SELECT'),
                       has_table_privilege(current_user, 'users', 'INSERT'),
                       has_table_privilege(current_user, 'users', 'UPDATE'),
                       has_table_privilege(current_user, 'users', 'DELETE')
                FROM pg_roles WHERE rolname = current_user
                """
            )
        ).one()

        assert role == ("sps_runtime", False, False, False, False, False, False, False, True, False, True, True, True, True)

    connection = engine.connect()
    try:
        with pytest.raises(DBAPIError, match="permission denied"):
            connection.exec_driver_sql("CREATE TABLE public.sps_runtime_ddl_probe (id integer)")
    finally:
        connection.rollback()
        connection.close()


def test_runtime_database_role_password_uses_a_salted_scram_verifier():
    password = "test-URL-safe_runtime-password"
    verifier = _scram_verifier(password)
    assert verifier.startswith("SCRAM-SHA-256$")
    assert password not in verifier
    assert verifier != _scram_verifier(password)


def test_runtime_role_gets_data_privileges_on_tables_created_by_future_migrations():
    if engine.dialect.name != "postgresql":
        pytest.skip("PostgreSQL default privileges are verified in CI")

    admin_url = os.environ["DATABASE_ADMIN_URL"]
    postgres_url = make_url(admin_url).set(drivername="postgresql").render_as_string(hide_password=False)
    table_name = f"sps_runtime_default_acl_{uuid4().hex}"
    with psycopg.connect(postgres_url) as admin:
        admin.execute(
            sql.SQL("CREATE TABLE public.{} (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text NOT NULL)").format(
                sql.Identifier(table_name)
            )
        )

    try:
        with engine.begin() as runtime:
            inserted_id = runtime.exec_driver_sql(
                f"INSERT INTO public.\"{table_name}\" (value) VALUES ('created') RETURNING id"
            ).scalar_one()
            runtime.exec_driver_sql(f"UPDATE public.\"{table_name}\" SET value = 'updated' WHERE id = {inserted_id}")
            assert runtime.exec_driver_sql(f'SELECT value FROM public."{table_name}" WHERE id = {inserted_id}').scalar_one() == "updated"
            runtime.exec_driver_sql(f'DELETE FROM public."{table_name}" WHERE id = {inserted_id}')
    finally:
        with psycopg.connect(postgres_url) as admin:
            admin.execute(sql.SQL("DROP TABLE public.{} CASCADE").format(sql.Identifier(table_name)))
